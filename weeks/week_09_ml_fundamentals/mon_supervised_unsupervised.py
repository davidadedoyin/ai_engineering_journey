# Day 1 practice: simple examples of supervised and unsupervised learning.

# Supervised example: a teacher gives labels.
# We know the answer for each example.
labels = {
    "house_size": [800, 1200, 1500],
    "house_price": [150000, 220000, 300000],
}
print("Supervised example:")
print(labels)

# Unsupervised example: we group items without labels.
customers = ["A", "B", "C", "D"]
print("\nUnsupervised example:")
print(customers)
